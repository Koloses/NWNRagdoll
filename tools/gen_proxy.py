#!/usr/bin/env python3
# generates src/proxy.cpp and src/dbghelp.def from a dbghelp.dll export list (Wine's x86_64 build)
import sys, pefile
src = sys.argv[1] if len(sys.argv) > 1 else '/usr/lib/x86_64-linux-gnu/wine/x86_64-windows/dbghelp.dll'
pe = pefile.PE(src)
names = [e.name.decode() for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name and not e.name.startswith(b'wine_')]
n = len(names)
c = ['// dbghelp.dll proxy (generated by tools/gen_proxy.py): every export jumps to the system dbghelp.dll;',
     '// names the system DLL does not have return 0', '#include <windows.h>',
     'static FARPROC g_fn[%d];' % n, 'static const char* g_names[%d] = {' % n]
for i in range(0, n, 4): c.append('  ' + ' '.join('"%s",' % x for x in names[i:i + 4]))
c += ['};', 'static __int64 Missing() { return 0; }', 'void Proxy_Load() {',
      '    char path[MAX_PATH]; GetSystemDirectoryA(path, MAX_PATH); lstrcatA(path, "\\\\dbghelp.dll");',
      '    HMODULE real = LoadLibraryA(path);',
      '    for (int i = 0; i < %d; i++) { g_fn[i] = real ? GetProcAddress(real, g_names[i]) : nullptr; if (!g_fn[i]) g_fn[i] = (FARPROC)Missing; }' % n,
      '}', '#define FWD(i, name) extern "C" __attribute__((naked)) void proxy_##name() { __asm__ __volatile__("jmp *%0" :: "m"(g_fn[i])); }']
for i, x in enumerate(names): c.append('FWD(%d, %s)' % (i, x))
open('src/proxy.cpp', 'w').write('\n'.join(c) + '\n')
open('src/dbghelp.def', 'w').write('\n'.join(['LIBRARY dbghelp.dll', 'EXPORTS'] + ['%s=proxy_%s @%d' % (x, x, i + 1) for i, x in enumerate(names)]) + '\n')
print(n, 'exports')
